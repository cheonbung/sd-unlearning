"""Phase 3 (#14): KID and FID-SD (distribution shift vs raw SD) over existing COCO images.

eval_coco_fid5k.py reports FID against *real* COCO photos (FID-real -> absolute quality scale).
Concept-Ablation / UCE additionally look at how far the edited model's output distribution drifts
from the *unedited* model (FID-SD / KID vs raw SD): for a localized edit, generic COCO output should
barely move. KID is the unbiased small-sample complement to FID (less biased at our N).

This reuses the COCO images already generated by eval_coco.py at eval/outputs/<model>/coco/ -- NO
regeneration. Any model with such a dir (>= MIN_IMGS) is scored against raw_v14's coco dir via
clean-fid: FID-SD = compute_fid(model, raw), KID = compute_kid(model, raw). raw_v14 vs itself = 0.

Generate the COCO dirs first if a model lacks one:
  python eval/eval_coco.py --models <key>          # writes eval/outputs/<key>/coco/

Run (WSL conda env lsse, has `cleanfid`):
  python models/fcf/eval_coco_kid.py --models raw_v14,odace_v3      # subset
  python models/fcf/eval_coco_kid.py                               # all on-disk coco dirs
"""
from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
FS_ROOT = REPO / "eval" / "outputs"
OUT_PATH = HERE / "coco_kid.json"
BASELINE = "raw_v14"
MIN_IMGS = 50  # clean-fid needs a reasonable sample; below this the number is meaningless

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")
logger = logging.getLogger("coco_kid")


def coco_dir(model: str) -> Path:
    return FS_ROOT / model / "coco"


def n_imgs(d: Path) -> int:
    return len(list(d.glob("*.png"))) if d.is_dir() else 0


def discover_models() -> list[str]:
    keys = sorted({p.parent.name for p in FS_ROOT.glob("*/coco") if n_imgs(p) >= MIN_IMGS})
    if BASELINE in keys:
        keys = [BASELINE] + [k for k in keys if k != BASELINE]
    return keys


def load_result() -> dict:
    if OUT_PATH.exists():
        try:
            return json.loads(OUT_PATH.read_text())
        except Exception:  # noqa: BLE001
            pass
    return {"_doc": "Phase 3 distribution shift vs raw SD over existing COCO images (no regen). "
                    "fid_sd/kid_sd = clean-fid distance of model coco dir vs raw_v14 coco dir; "
                    "lower = more localized edit. raw_v14 vs itself = 0.",
            "baseline": BASELINE, "min_imgs": MIN_IMGS, "models": {}}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default=None, help="comma list; default = all on-disk coco dirs")
    args = ap.parse_args()

    from cleanfid import fid

    ref = coco_dir(BASELINE)
    if n_imgs(ref) < MIN_IMGS:
        logger.error("baseline coco dir missing/small: %s (n=%d). Run eval_coco.py --models %s",
                     ref, n_imgs(ref), BASELINE)
        return

    models = ([m.strip() for m in args.models.split(",") if m.strip()]
              if args.models else discover_models())
    out = load_result()

    for model in models:
        d = coco_dir(model)
        nm = n_imgs(d)
        if nm < MIN_IMGS:
            logger.warning("skip %s: coco dir n=%d < %d (generate via eval_coco.py)", model, nm, MIN_IMGS)
            continue
        logger.info(">>> %s (n=%d)", model, nm)
        if model == BASELINE:
            rec = {"n": nm, "fid_sd": 0.0, "kid_sd": 0.0}
        else:
            try:
                fid_sd = round(fid.compute_fid(str(d), str(ref), mode="clean", verbose=False), 3)
            except Exception as e:  # noqa: BLE001
                logger.exception("FID failed %s: %s", model, e)
                fid_sd = None
            try:
                kid_sd = round(fid.compute_kid(str(d), str(ref), verbose=False) * 1000, 4)  # x1e3
            except Exception as e:  # noqa: BLE001
                logger.warning("KID failed %s: %s", model, e)
                kid_sd = None
            rec = {"n": nm, "fid_sd": fid_sd, "kid_sd": kid_sd}
        out["models"][model] = rec
        OUT_PATH.write_text(json.dumps(out, indent=2))  # incremental
        logger.info("=== %s: FID-SD=%s KID-SD(x1e3)=%s ===", model, rec["fid_sd"], rec["kid_sd"])

    logger.info("wrote %s", OUT_PATH)
    print("COCO_KID_DONE_OK")


if __name__ == "__main__":
    main()
